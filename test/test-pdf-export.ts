import { buildVendorRegistryPDF, VendorPDFRecord } from "../lib/vendor-registry-pdf";
import fs from "fs";
import path from "path";

// 1. Single-page test with genuine sample data
const sampleVendors: VendorPDFRecord[] = [
  {
    id: "BUT-V-000002",
    businessName: "ULO SA TAO RESTAURANT & CATERING SERVICES",
    ownerName: "Ma. Irish Relleta",
    barangay: "Holy Redeemer Pob.",
    category: "Food & Refreshment / Eatery / Market Stall",
    status: "Certified Active",
  },
  {
    id: "BUT-V-000003",
    businessName: "Montilla Street Produce & General Supplies with a Very Long Commercial Business Name for Testing Text Wrapping",
    ownerName: "Juan Dela Cruz",
    barangay: "Urduja",
    category: "Produce & Snacks",
    status: "Certified Active",
  },
];

const doc1 = buildVendorRegistryPDF({
  vendors: sampleVendors,
  totalRegistryCount: 2,
  selectedBarangay: "All",
  selectedCategory: "All",
  searchQuery: "",
  exportDate: new Date("2026-10-13T17:30:00+08:00"),
});

const pdf1Output = Buffer.from(doc1.output("arraybuffer"));
console.log("Test 1 (Single Page): Generated bytes =", pdf1Output.length);
console.log("Test 1: Total pages =", doc1.getNumberOfPages());
if (!pdf1Output.toString().startsWith("%PDF-")) {
  throw new Error("Test 1 failed: Not a valid PDF header");
}

// 2. Multi-page test with 50 vendor records to verify multi-page pagination & repeated headers
const multiVendors: VendorPDFRecord[] = Array.from({ length: 50 }, (_, i) => ({
  id: `BUT-V-${String(i + 1).padStart(6, "0")}`,
  businessName: `Vendor Business ${i + 1} - Official Registered Enterprise in Butuan City`,
  ownerName: `Proprietor ${i + 1} Santos`,
  barangay: i % 2 === 0 ? "Urduja" : "Ampayon",
  category: i % 3 === 0 ? "Food & Beverage" : "Dry Goods",
  status: "Certified Active",
}));

const doc2 = buildVendorRegistryPDF({
  vendors: multiVendors,
  totalRegistryCount: 50,
  selectedBarangay: "All",
  selectedCategory: "All",
  searchQuery: "",
  exportDate: new Date("2026-10-13T17:30:00+08:00"),
});

const pdf2Output = Buffer.from(doc2.output("arraybuffer"));
console.log("Test 2 (Multi Page): Generated bytes =", pdf2Output.length);
console.log("Test 2: Total pages =", doc2.getNumberOfPages());
if (doc2.getNumberOfPages() < 2) {
  throw new Error("Test 2 failed: Expected multiple pages for 50 records");
}

// 3. Filtered registry test
const filteredVendors = multiVendors.filter((v) => v.barangay === "Urduja");
const doc3 = buildVendorRegistryPDF({
  vendors: filteredVendors,
  totalRegistryCount: 50,
  selectedBarangay: "Urduja",
  selectedCategory: "Food & Beverage",
  searchQuery: "Business 1",
  exportDate: new Date("2026-10-13T17:30:00+08:00"),
});

const pdf3Output = Buffer.from(doc3.output("arraybuffer"));
console.log("Test 3 (Filtered): Generated bytes =", pdf3Output.length);
console.log("Test 3: Vendor count =", filteredVendors.length);

// Save sample output to scratch directory for inspection
const outDir = path.join(__dirname, "output");
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "test_registry_export.pdf"), pdf1Output);
fs.writeFileSync(path.join(outDir, "test_multipage_export.pdf"), pdf2Output);
console.log("All PDF generator unit tests passed successfully!");
